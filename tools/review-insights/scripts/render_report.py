#!/usr/bin/env python3
"""Render the rule catalogue (RULES.md) and the summary tables used in
PROPOSAL.md from the consolidated rules.

Usage: render_report.py <rules.json> <threads.jsonl> <out-dir>
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from canon import GROUPS, TODAY  # noqa: E402

REPO = "https://github.com/mozilla/application-services"
TIERS = {
    0: "Tier 0 · config only",
    1: "Tier 1 · small script / ast-grep",
    2: "Tier 2 · custom tooling",
    3: "Tier 3 · review checklist",
}


def score(rule):
    return rule["review_prs_min"] + 2 * len(rule["bugfix_prs"]) + rule["periods_seen"]


def clean_quote(text, limit=220):
    text = re.sub(r"```suggestion\s*", "suggested: ", text)
    text = text.replace("```", "").replace("|", "\\|")
    text = re.sub(r"\s+", " ", text).strip()
    text = text.replace("<", "&lt;").replace(">", "&gt;")
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + " …"


def evidence_line(rule):
    parts = [f"{rule['review_threads']} review threads in ≥{rule['review_prs_min']} PRs",
             f"seen in {rule['periods_seen']}/7 periods"]
    if rule["bugfix_prs"]:
        n = len(rule["bugfix_prs"])
        parts.append(f"{n} bugfix PR{'s' if n > 1 else ''}")
    return " · ".join(parts)


def main():
    rules_path, threads_path, out = sys.argv[1:4]
    data = json.load(open(rules_path))
    dates = {}
    with open(threads_path) as f:
        for line in f:
            t = json.loads(line)
            dates[t["url"]] = t["created_at"][:10]
    rules = sorted(data["rules"], key=lambda r: -score(r))

    lines = [
        "# Rule catalogue",
        "",
        "Generated by `scripts/render_report.py` from `results/rules.json`; see [PROPOSAL.md](PROPOSAL.md) for the "
        "method and the rollout proposal.",
        "",
        "Each rule merges near-duplicate findings from the 7 review periods (2022 → 2026-10) and from the "
        "bugfix-PR analysis. **Threads** is the number of review threads the extraction counted, and **≥ PRs** "
        "the number of distinct PRs in the sampled evidence (a lower bound: one review can raise the same point "
        "many times). **Periods** shows how persistent the issue is. **Today** is what the check finds on "
        "`main` (5335439) now.",
        "",
        "Tiers: " + " · ".join(TIERS.values()),
        "",
    ]
    for group, title in GROUPS.items():
        in_group = [r for r in rules if r["group"] == group]
        if not in_group:
            continue
        lines += [f"- [{title}](#{re.sub(r'[^a-z0-9 -]', '', title.lower()).replace(' ', '-')}) ({len(in_group)})"]
    lines.append("")

    for group, title in GROUPS.items():
        in_group = [r for r in rules if r["group"] == group]
        if not in_group:
            continue
        lines += [f"## {title}", ""]
        for r in in_group:
            lines += [f"### `{r['id']}`", "", f"**{r['title']}**", "",
                      f"- **Evidence:** {evidence_line(r)}",
                      f"- **Enforcement:** {TIERS[r['tier']]}",
                      f"- **How:** {r['how']}"]
            if r["id"] in TODAY:
                lines.append(f"- **Today:** {TODAY[r['id']]}")
            if r["evidence"]:
                lines.append("- **From reviews:**")
                for e in r["evidence"]:
                    lines.append(f"  - [#{e['pr']}]({e['url']}) ({dates.get(e['url'], '')}): “{clean_quote(e['quote'])}”")
            if r["bugfix_prs"]:
                lines.append("- **Bugfixes it targets:**")
                for b in r["bugfix_prs"][:8]:
                    verdict = {"yes": "preventable", "partially": "partially preventable"}.get(b["preventable"], b["preventable"] or "")
                    lines.append(f"  - [#{b['pr']}]({b['url']}) {clean_quote(b['bug'] or b['title'], 160)} _({verdict})_")
            lines.append("")
    open(os.path.join(out, "RULES.md"), "w").write("\n".join(lines))

    # Summary tables for PROPOSAL.md.
    top = ["| # | Rule | Area | Threads (≥ PRs) | Periods | Bugfix PRs | Tier |",
           "|---:|---|---|---:|---:|---:|---|"]
    for i, r in enumerate(rules[:25], 1):
        top.append(f"| {i} | [{r['title']}](RULES.md#{r['id']}) | {r['group_title']} | {r['review_threads']} (≥{r['review_prs_min']}) "
                   f"| {r['periods_seen']}/7 | {len(r['bugfix_prs']) or ''} | {r['tier']} |")
    uniffi = ["| Rule | Threads (≥ PRs) | Bugfix PRs | Tier | Today |", "|---|---:|---:|---|---|"]
    for r in [r for r in rules if r["group"] == "uniffi"]:
        uniffi.append(f"| [{r['title']}](RULES.md#{r['id']}) | {r['review_threads']} (≥{r['review_prs_min']}) | "
                      f"{len(r['bugfix_prs']) or ''} | {r['tier']} | {TODAY.get(r['id'], '')} |")
    tiers = {t: [r for r in rules if r["tier"] == t] for t in TIERS}
    tier_table = ["| Tier | Rules | Review threads covered |", "|---|---:|---:|"]
    for t, rs in tiers.items():
        tier_table.append(f"| {TIERS[t]} | {len(rs)} | {sum(r['review_threads'] for r in rs)} |")
    fixes = ["| Rule | Bugfix PRs (preventable / partially) |", "|---|---|"]
    by_rule = []
    for r in rules:
        yes = [b for b in r["bugfix_prs"] if b["preventable"] == "yes"]
        part = [b for b in r["bugfix_prs"] if b["preventable"] == "partially"]
        if yes or part:
            by_rule.append((len(yes) * 2 + len(part), r, yes, part))
    for _, r, yes, part in sorted(by_rule, key=lambda x: -x[0]):
        links = ", ".join(f"[#{b['pr']}]({b['url']})" for b in yes)
        plinks = ", ".join(f"[#{b['pr']}]({b['url']})" for b in part)
        fixes.append(f"| [{r['title']}](RULES.md#{r['id']}) | {links or '–'} / {plinks or '–'} |")
    open(os.path.join(out, "summary_tables.md"), "w").write(
        "## top\n\n" + "\n".join(top) + "\n\n## uniffi\n\n" + "\n".join(uniffi) +
        "\n\n## tiers\n\n" + "\n".join(tier_table) + "\n\n## fixes\n\n" + "\n".join(fixes) + "\n")


if __name__ == "__main__":
    main()
